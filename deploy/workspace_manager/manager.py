def daemon_available():
    _, _, code = docker("version", "--format", "{{.Server.Version}}", check=False, timeout=15)
    return code == 0


class Handler(BaseHTTPRequestHandler):
    server_version = "ShamsWorkspaceManager"
    protocol_version = "HTTP/1.1"

    def log_message(self, *_args):
        pass

    def authorized(self):
        if not TOKEN:
            return False
        supplied = self.headers.get("X-Shams-Token", "")
        return hmac.compare_digest(supplied, TOKEN)

    def json_out(self, status, payload):
        body = json.dumps(payload).encode()
        self.send_response(status)
        self.send_header("content-type", "application/json")
        self.send_header("content-length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def raw_out(self, status, body, content_type="application/octet-stream", headers=None):
        self.send_response(status)
        self.send_header("content-type", content_type)
        self.send_header("content-length", str(len(body)))
        for key, value in (headers or {}).items():
            if key.lower() not in ("transfer-encoding", "connection", "content-length"):
                self.send_header(key, value)
        self.end_headers()
        self.wfile.write(body)

    def read_body(self):
        length = int(self.headers.get("content-length") or 0)
        return self.rfile.read(length) if length else b""

    def parsed(self, body):
        if not body:
            return {}
        try:
            loaded = json.loads(body)
        except json.JSONDecodeError as exc:
            raise Failure(400, "body must be JSON") from exc
        if not isinstance(loaded, dict):
            raise Failure(400, "body must be a JSON object")
        return loaded

    def do_GET(self):
        self.dispatch("GET")

    def do_HEAD(self):
        self.dispatch("HEAD")

    def do_POST(self):
        self.dispatch("POST")

    def do_DELETE(self):
        self.dispatch("DELETE")

    def dispatch(self, method):
        parsed_url = urllib.parse.urlparse(self.path)
        parts = [segment for segment in parsed_url.path.split("/") if segment]
        query = urllib.parse.parse_qs(parsed_url.query)
        try:
            if parts == ["healthz"]:
                self.json_out(200, {"docker": daemon_available(), "service": "shams-workspace-manager"})
                return
            if not self.authorized():
                raise Failure(401, "unauthorized")
            self.route(method, parts, query, parsed_url.query)
        except Failure as failure:
            self.json_out(failure.status, {"error": failure.message})
        except Exception as error:  # never leak a traceback, never claim success
            self.json_out(500, {"error": f"{type(error).__name__}: {str(error)[:300]}"})

    def route(self, method, parts, query, raw_query=""):
        if parts[:1] == ["preview"] and method in ALLOWED_PREVIEW_METHODS and len(parts) >= 3:
            workspace_id, port = parts[1], parts[2]
            path = "/" + "/".join(parts[3:])
            envelope = proxy_preview(
                workspace_id, port, path, raw_query, dict(self.headers),
                b"" if method in ("GET", "HEAD") else self.read_body(),
                method=method,
            )
            body = base64.b64decode(envelope.get("body_b64") or "")
            headers = {
                key: value for key, value in (envelope.get("headers") or {}).items()
                if key.lower() not in ("content-type", "transfer-encoding", "content-length", "connection")
            }
            content_type = (envelope.get("headers") or {}).get("Content-Type", "text/html; charset=utf-8")
            self.raw_out(int(envelope.get("status") or 502), body, content_type, headers)
            return

        if parts == ["workspaces"] and method == "POST":
            self.json_out(201, create_workspace(self.parsed(self.read_body())))
            return

        if len(parts) >= 2 and parts[0] == "workspaces":
            workspace_id = parts[1]
            action = parts[2] if len(parts) > 2 else None
            if action is None:
                if method == "GET":
                    self.json_out(200, workspace_status(workspace_id))
                elif method == "DELETE":
                    self.json_out(200, destroy_workspace(workspace_id, purge_volume=query.get("volume", ["1"])[0] != "0"))
                else:
                    raise Failure(405, "method not allowed")
                return

            if action == "files":
                if method == "POST":
                    body = self.parsed(self.read_body())
                    raw = body.get("content_b64")
                    if raw is None:
                        raise Failure(400, "content_b64 required")
                    try:
                        content = base64.b64decode(str(raw), validate=True)
                    except Exception as exc:
                        raise Failure(400, "content_b64 is not valid base64") from exc
                    self.json_out(200, write_file(workspace_id, body.get("path"), content))
                    return
                if method == "GET":
                    self.json_out(200, list_files(workspace_id, query.get("limit", [None])[0]))
                    return
                if method == "DELETE":
                    self.json_out(200, remove_file(workspace_id, query.get("path", [""])[0]))
                    return

            if action == "contents" and method == "GET":
                self.json_out(200, read_file(workspace_id, query.get("path", [""])[0]))
                return

            if action == "exec" and method == "POST":
                body = self.parsed(self.read_body())
                self.json_out(200, execute(workspace_id, body.get("argv"), body.get("timeout"), body.get("env")))
                return

            if action == "install" and method == "POST":
                body = self.parsed(self.read_body())
                self.json_out(200, install_dependencies(workspace_id, body.get("requirements", ""), body.get("timeout")))
                return

            if action == "logs":
                self.json_out(200, preview_logs(workspace_id, query.get("tail", [None])[0]))
                return

            if action == "export" and method == "GET":
                self.json_out(200, export_workspace(workspace_id))
                return

            if action == "preview":
                if method == "POST":
                    body = self.parsed(self.read_body())
                    self.json_out(200, start_preview(workspace_id, body.get("argv"), body.get("port"),
                                                      body.get("probe_path", "/")))
                    return
                if method == "DELETE":
                    self.json_out(200, stop_preview(workspace_id))
                    return
                if method == "GET":
                    self.json_out(200, preview_state(workspace_id))
                    return

        raise Failure(404, "no such endpoint")


def main():
    if not TOKEN:
        print("SHAMS_WS_TOKEN is required; refusing to serve", flush=True)
        raise SystemExit(1)
    print(f"workspace manager on :{LISTEN_PORT}, runtimes={list(RUNTIMES)}, docker={daemon_available()}", flush=True)
    ThreadingHTTPServer((LISTEN_HOST, LISTEN_PORT), Handler).serve_forever()


if __name__ == "__main__":
    main()
