class Failure(Exception):
    def __init__(self, status, message):
        super().__init__(message)
        self.status = status
        self.message = message


def docker(*argv, timeout=60, binary=False, stdin=None, check=True,
           max_output_bytes=DOCKER_OUTPUT_BYTES, fail_on_output_limit=False):
    """Run docker without a shell while draining both pipes into bounded buffers."""
    command = ["docker", *argv]
    process = subprocess.Popen(
        command,
        stdin=subprocess.PIPE if stdin is not None else subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        bufsize=0,
    )
    selector = selectors.DefaultSelector()
    streams = {"stdout": bytearray(), "stderr": bytearray()}
    sizes = {"stdout": 0, "stderr": 0}
    pending = memoryview(stdin or b"")
    sent = 0
    deadline = time.monotonic() + timeout

    try:
        for name in ("stdout", "stderr"):
            stream = getattr(process, name)
            os.set_blocking(stream.fileno(), False)
            selector.register(stream, selectors.EVENT_READ, name)
        if stdin is not None:
            os.set_blocking(process.stdin.fileno(), False)
            selector.register(process.stdin, selectors.EVENT_WRITE, "stdin")

        while selector.get_map():
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise subprocess.TimeoutExpired(command, timeout)
            for key, _ in selector.select(remaining):
                name = key.data
                stream = key.fileobj
                try:
                    if name == "stdin":
                        written = os.write(stream.fileno(), pending[sent:sent + 65536])
                        sent += written
                        if sent == len(pending):
                            selector.unregister(stream)
                            stream.close()
                        continue
                    chunk = os.read(stream.fileno(), 65536)
                except BlockingIOError:
                    continue
                except BrokenPipeError:
                    selector.unregister(stream)
                    stream.close()
                    continue
                if not chunk:
                    selector.unregister(stream)
                    stream.close()
                    continue
                sizes[name] += len(chunk)
                room = max_output_bytes - len(streams[name])
                if room > 0:
                    streams[name].extend(chunk[:room])

        returncode = process.wait(timeout=max(0.01, deadline - time.monotonic()))
    except subprocess.TimeoutExpired as exc:
        process.kill()
        process.wait()
        raise Failure(504, "docker command timed out") from exc
    finally:
        selector.close()
        for stream in (process.stdin, process.stdout, process.stderr):
            if stream is not None and not stream.closed:
                stream.close()

    if fail_on_output_limit and any(size > max_output_bytes for size in sizes.values()):
        raise Failure(413, "docker command output exceeded the allowed size")
    if check and returncode != 0:
        detail = bytes(streams["stderr"]).decode("utf-8", "replace").strip()[:2000]
        raise Failure(502, f"docker {argv[0]} failed: {detail}")
    if binary:
        return bytes(streams["stdout"]), bytes(streams["stderr"]), returncode
    return (
        streams["stdout"].decode("utf-8", "replace"),
        streams["stderr"].decode("utf-8", "replace"),
        returncode,
    )


def limit_for(key, value):
    low, high, default = LIMITS[key]
    try:
        number = default if value is None else float(value)
    except (TypeError, ValueError):
        return default
    number = int(number) if key != "cpus" else number
    return max(low, min(high, number))


def safe_workspace_id(raw):
    if not WORKSPACE_ID.match(str(raw or "")):
        raise Failure(400, "workspace id rejected")
    return raw


def safe_relative_path(raw):
    """Reject absolute paths, traversal and every . or .. component.

    Returning the posix-normalised string is not enough: /workspace is the only
    namespace, and the container resolves it, so we keep the components exactly
    as given once they are proven safe. Spaces are ordinary characters here.
    """
    text = str(raw or "")
    if not text or text.startswith("/") or "\x00" in text or "\\" in text:
        raise Failure(400, "path rejected")
    parts = text.split("/")
    if any(part in ("", ".", "..") for part in parts):
        raise Failure(400, "path rejected")
    if len(text) > 512:
        raise Failure(400, "path rejected")
    return "/".join(parts)


def container_name(workspace_id):
    return f"{CONTAINER_PREFIX}{workspace_id}"


def volume_name(workspace_id):
    return f"{VOLUME_PREFIX}{workspace_id}"


def inspect_state(workspace_id):
    out, _, code = docker(
        "inspect",
        "--format",
        "{{.State.Status}}|{{.State.ExitCode}}|{{.Config.Image}}",
        container_name(workspace_id),
        check=False,
    )
    if code != 0:
        return {"state": "absent", "exit_code": None, "image": None}
    status, exit_code, image = (out.strip() + "||").split("|")[:3]
    return {"state": status, "exit_code": int(exit_code or 0), "image": image or None}


def require_running(workspace_id):
    state = inspect_state(workspace_id)
    if state["state"] == "exited":
        # A daemon restart leaves every workspace stopped: --restart no is
        # deliberate, so waking it up is an explicit, owned action here.
        docker("start", container_name(workspace_id), check=False, timeout=60)
        for _ in range(10):
            state = inspect_state(workspace_id)
            if state["state"] == "running":
                break
            time.sleep(0.3)
    if state["state"] != "running":
        raise Failure(409, f"workspace is {state['state']}")
    return state


