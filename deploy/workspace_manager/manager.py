def execute(workspace_id, argv, timeout=None, env=None):
    safe_workspace_id(workspace_id)
    require_running(workspace_id)
    if not isinstance(argv, list) or not argv or not all(isinstance(part, str) for part in argv):
        raise Failure(400, "argv must be a non-empty array of strings")
    if len(argv) > 32:
        raise Failure(400, "too many arguments")
    if any("\x00" in part or len(part) > 4096 for part in argv):
        raise Failure(400, "argument rejected")
    budget = int(limit_for("exec_timeout", timeout))
    ceiling = int(limit_for("output_bytes", None))

    env_args = []
    if isinstance(env, dict) and env:
        if len(env) > 20:
            raise Failure(400, "too many environment variables")
        for key, value in list(env.items())[:20]:
            if not re.match(r"\A[A-Z_][A-Z0-9_]{0,63}\Z", str(key)):
                raise Failure(400, f"environment variable name rejected: {key[:32]}")
            env_args += ["--env", f"{key}={str(value)[:2000]}"]

    args = ["exec", *env_args, "-w", "/workspace", container_name(workspace_id),
            # Enforced inside the container, not only on the client side: killing
            # the docker exec client would leave the process running in there.
            # -k is the kill-after grace period; a SIGKILL escape cannot hang.
            "/usr/bin/timeout", "-k", "5", str(budget), *argv]

    started = time.monotonic()
    try:
        out, err, code = docker(*args, timeout=budget + 20, binary=True, check=False)
    except Failure as interruption:
        if interruption.status != 504:
            raise
        # The daemon itself stopped answering. The in-container timeout still
        # fires, so nothing here needs to chase the process; report honestly.
        return {
            "ok": False, "exit_code": None, "duration_seconds": budget,
            "stdout": "", "stderr": f"execution timed out after {budget}s",
            "timed_out": True,
        }
    duration = round(time.monotonic() - started, 2)
    stdout_text = clip(out, ceiling)
    stderr_text = clip(err, ceiling)
    # GNU timeout reports 124 on SIGTERM and 137 when the kill timer fired.
    if code in (124, 137):
        return {
            "ok": False, "exit_code": code, "duration_seconds": duration,
            "stdout": stdout_text,
            "stderr": (stderr_text + f"\nexecution exceeded the {budget}s limit").strip(),
            "timed_out": True,
        }
    return {
        "ok": code == 0,
        "exit_code": code,
        "duration_seconds": duration,
        "stdout": stdout_text,
        "stderr": stderr_text,
        "timed_out": False,
    }


def clip(raw, ceiling):
    text = raw.decode("utf-8", "replace")
    if len(text) <= ceiling:
        return text
    return text[:ceiling] + f"\n… truncated at {ceiling} bytes"


def install_dependencies(workspace_id, requirements_text, timeout=180):
    """Install through the allowlist proxy only.

    The execution container stays on --network none. A helper container on the
    internal egress network shares its volume and is the only thing that can
    reach the index, and that helper can only reach APPROVED_INDEX_HOSTS.
    """
    safe_workspace_id(workspace_id)
    require_running(workspace_id)
    lines = [line.strip() for line in requirements_text.splitlines() if line.strip() and not line.strip().startswith("#")]
    if len(lines) > 40:
        raise Failure(400, "too many requirements")
    for line in lines:
        if not re.match(r"\A[A-Za-z0-9][A-Za-z0-9._-]*(\[[A-Za-z0-9,._-]+\])?([<>=!~]=?[0-9][0-9A-Za-z.*+!-_]*)?\Z", line):
            raise Failure(400, f"requirement rejected: {line[:80]}")

    payload = "\n".join(lines) + "\n"
    # Stage inside the volume, not the container's private /tmp: the helper that
    # actually installs is a different container and must see the same bytes.
    docker("exec", "-i", container_name(workspace_id),
           "dd", "of=/workspace/requirements.txt", "bs=1M",
           stdin=payload.encode(), check=False, timeout=30)

    shared = [
        "run", "--rm",
        "--network", EGRESS_NETWORK,
        "--volume", f"{volume_name(workspace_id)}:/workspace",
        "--user", "1000:1000",
        "--workdir", "/workspace",
        "--env", "HOME=/tmp",
        "--env", "PIP_NO_CACHE_DIR=1",
        "--env", "PIP_DISABLE_PIP_VERSION_CHECK=1",
        "--env", f"HTTPS_PROXY={PROXY_URL}",
        "--env", f"HTTP_PROXY={PROXY_URL}",
        "--env", "NO_PROXY=localhost,127.0.0.1",
        "--cap-drop", "ALL",
        "--security-opt", "no-new-privileges",
        "--pids-limit", "256",
        "--memory", "1024m",
        "--cpus", "1.0",
        "--read-only",
        "--tmpfs", "/tmp:size=512m",
    ]
    out, err, code = docker(
        *shared, RUNTIMES["python3"],
        "python3", "-m", "venv", "--clear", "/workspace/.venv",
        timeout=120, check=False,
    )
    if code != 0:
        raise Failure(500, f"venv creation failed: {(err or out)[-400:]}")

    out, err, code = docker(
        *shared, RUNTIMES["python3"],
        "/workspace/.venv/bin/python", "-m", "pip", "install", "-r", "/workspace/requirements.txt",
        timeout=int(limit_for("exec_timeout", timeout)) + 120, check=False,
    )
    if code != 0:
        return {"ok": False, "installed": [], "output": clip((err or out).encode(), 40_000)}
    listing, _, _ = docker(
        "run", "--rm",
        "--volume", f"{volume_name(workspace_id)}:/workspace",
        "--network", "none",
        "--read-only",
        "--entrypoint", "/bin/sh", RUNTIMES["python3"],
        "-c", "ls /workspace/.venv/lib/python*/site-packages 2>/dev/null | head -40",
        check=False, timeout=60,
    )
    packages = [name for name in listing.split() if name and not name.endswith((".dist-info", ".txt", ".pth"))]
    return {"ok": True, "installed": packages, "output": clip((err or out).encode(), 40_000)}


# ---------------------------------------------------------------------------
# preview
# ---------------------------------------------------------------------------
#
# The preview server runs in its own container, sharing only the workspace
# volume. That buys three things: `docker logs` becomes a real log source for
# the panel, stopping is deterministic (remove the container, no process
# chasing), and the execution container keeps running its sleep forever so a
# crashed preview never takes the workspace down with it. It is still
# --network none: the request is made from inside the preview container against
# its own loopback, so nothing ever listens on an address a user could reach.

def preview_container(workspace_id):
    return f"{CONTAINER_PREFIX}{workspace_id}-preview"


def preview_state(workspace_id):
    out, _, code = docker(
        "inspect", "--format", "{{.State.Status}}|{{.State.ExitCode}}",
        preview_container(workspace_id), check=False,
    )
    if code != 0:
        return {"state": "absent", "exit_code": None, "container": None}
    status, exit_code = (out.strip() + "|0").split("|")[:2]
    return {"state": status, "exit_code": int(exit_code or 0), "container": preview_container(workspace_id)}


def start_preview(workspace_id, argv, port, probe_path="/"):
    safe_workspace_id(workspace_id)
    require_running(workspace_id)
    if not isinstance(argv, list) or not argv or not all(isinstance(part, str) for part in argv):
        raise Failure(400, "preview command must be a non-empty array of strings")
    if len(argv) > 32 or any("\x00" in part or len(part) > 4096 for part in argv):
        raise Failure(400, "preview command rejected")
    try:
        number = int(port)
    except (TypeError, ValueError) as exc:
        raise Failure(400, "preview port must be an integer") from exc
    if not (1024 <= number <= 65535):
        raise Failure(400, "preview port out of range")

    docker("rm", "-f", preview_container(workspace_id), check=False, timeout=60)
    out, err, code = docker(
        "run", "-d",
        "--name", preview_container(workspace_id),
        "--hostname", "preview",
        "--label", f"shams.workspace={workspace_id}",
        "--label", "shams.role=preview",
        "--user", "1000:1000",
        "--workdir", "/workspace",
        "--env", "HOME=/tmp",
        "--volume", f"{volume_name(workspace_id)}:/workspace",
        "--network", "none",
        "--read-only",
        "--tmpfs", f"/tmp:size={int(limit_for('tmpfs_mb', None))}m",
        "--cap-drop", "ALL",
        "--security-opt", "no-new-privileges",
        "--pids-limit", str(int(limit_for("pids", None))),
        "--memory", f"{int(limit_for('memory_mb', None))}m",
        "--memory-swap", f"{int(limit_for('memory_mb', None))}m",
        "--cpus", str(limit_for("cpus", None)),
        "--restart", "no",
        RUNTIMES["python3"],
        *argv,
        timeout=120, check=False,
    )
    if code != 0:
        raise Failure(503, f"preview container failed to start: {(err or out).strip()[:1200]}")

    deadline = time.monotonic() + 30
    last = ""
    while time.monotonic() < deadline:
        state = preview_state(workspace_id)
        if state["state"] != "running":
            logs, _, _ = docker("logs", "--tail", "40", preview_container(workspace_id), check=False)
            raise Failure(409, f"preview process exited ({state['state']}): {logs[-1200:]}")
        probe, probe_err, probe_code = docker(
            "exec", preview_container(workspace_id),
            "python3", "-c", PROBE_SNIPPET, str(number), str(probe_path)[:200],
            check=False, timeout=20,
        )
        last = (probe + probe_err).strip()
        if probe_code == 0 and last.startswith("PROBE_OK"):
            with LOCK:
                PREVIEWS[workspace_id] = {"port": number}
            return {"ok": True, "port": number, "reachable": True, "detail": last,
                    "container": preview_container(workspace_id)}
        time.sleep(1.0)
    logs, _, _ = docker("logs", "--tail", "40", preview_container(workspace_id), check=False)
    docker("rm", "-f", preview_container(workspace_id), check=False, timeout=60)
    raise Failure(409, f"nothing answered on port {number} within 30s: {last[-300:]}\n{logs[-1200:]}")


