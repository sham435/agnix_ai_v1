def stop_preview(workspace_id):
    safe_workspace_id(workspace_id)
    docker("rm", "-f", preview_container(workspace_id), check=False, timeout=60)
    with LOCK:
        PREVIEWS.pop(workspace_id, None)
    return {"ok": True, "preview": preview_state(workspace_id)}


def preview_logs(workspace_id, tail=200):
    safe_workspace_id(workspace_id)
    lines = int(max(1, min(1000, int(tail or 200))))
    out, err, code = docker(
        "logs", "--tail", str(lines), preview_container(workspace_id),
        binary=True, check=False, timeout=30,
    )
    if code != 0:
        return {"stdout": "", "stderr": err.decode("utf-8", "replace")[:2000]}
    return {"stdout": out.decode("utf-8", "replace")[-200_000:],
            "stderr": err.decode("utf-8", "replace")[-50_000:]}



def proxy_preview(workspace_id, port, path, query, headers, body, method="GET", timeout=20):
    """Forward one preview request from inside the workspace.

    The execution container has no published port and no inbound route, so the
    request is made from inside it against its own loopback and the response is
    handed back. Users never control a destination: only this workspace id, a
    port the workspace itself opened, and a path.
    """
    safe_workspace_id(workspace_id)
    if method.upper() not in ALLOWED_PREVIEW_METHODS:
        raise Failure(405, f"preview forwards only {', '.join(sorted(ALLOWED_PREVIEW_METHODS))}")
    try:
        number = int(port)
    except (TypeError, ValueError) as exc:
        raise Failure(400, "preview port must be an integer") from exc
    if not (1024 <= number <= 65535):
        raise Failure(400, "preview port out of range")
    if preview_state(workspace_id)["state"] != "running":
        raise Failure(409, "no preview is running for this workspace")
    with LOCK:
        opened = PREVIEWS.get(workspace_id)
    if not opened:
        raise Failure(409, "this manager lost track of the preview; start it again")
    if int(opened["port"]) != number:
        raise Failure(403, f"this preview session opened port {opened['port']}, not {number}")
    if not path.startswith("/"):
        path = "/" + path

    request_headers = {}
    for key, value in headers.items():
        lowered = key.lower()
        if lowered in ("host", "content-length", "connection", "x-shams-token", "accept-encoding"):
            continue
        if lowered.startswith(("x-shams-", "sec-websocket")) or lowered in (
            "user-agent", "referer", "cookie", "content-type", "accept", "accept-language",
            "upgrade", "origin",
        ):
            request_headers[key] = value

    payload = {
        "method": method.upper(),
        "path": path[:2000],
        "query": (query or "")[:4000],
        "headers": request_headers,
        "body": base64.b64encode(body or b"").decode(),
    }
    out, err, code = docker(
        "exec", "-i", preview_container(workspace_id),
        "python3", "-c", PROXY_SNIPPET, str(number), json.dumps(payload),
        binary=True, check=False, timeout=timeout,
    )
    if code != 0:
        raise Failure(502, f"preview request failed: {(err.decode('utf-8', 'replace') or out.decode('utf-8','replace'))[-400:]}")
    try:
        envelope = json.loads(out.decode("utf-8", "replace"))
    except json.JSONDecodeError as exc:
        raise Failure(502, "preview returned unreadable data") from exc
    return envelope


