EXPORT_SNIPPET = r"""
import os, sys, zipfile
compressed_limit, uncompressed_limit = int(sys.argv[1]), int(sys.argv[2])
root = os.environ.get("SHAMS_EXPORT_ROOT", "/workspace")
skip_dirs = {".venv", "__pycache__", ".git", ".pytest_cache"}
class ExportLimit(RuntimeError):
    pass
class LimitedWriter:
    def __init__(self, stream, limit):
        self.stream, self.limit, self.total = stream, limit, 0
    def write(self, data):
        self.total += len(data)
        if self.total > self.limit:
            raise ExportLimit("compressed archive limit exceeded")
        return self.stream.write(data)
    def tell(self):
        return self.total
    def flush(self):
        self.stream.flush()
writer = LimitedWriter(sys.stdout.buffer, compressed_limit)
uncompressed = 0
try:
    with zipfile.ZipFile(writer, "w", zipfile.ZIP_DEFLATED) as archive:
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(d for d in dirnames if d not in skip_dirs)
            for name in sorted(filenames):
                full = os.path.join(dirpath, name)
                if not os.path.isfile(full):
                    continue
                try:
                    size = os.path.getsize(full)
                    uncompressed += size
                    if uncompressed > uncompressed_limit:
                        raise ExportLimit("uncompressed archive limit exceeded")
                    archive.write(full, os.path.relpath(full, root))
                except OSError:
                    continue
    writer.flush()
except ExportLimit as error:
    print(str(error), file=sys.stderr)
    sys.exit(3)
"""


def export_workspace(workspace_id):
    safe_workspace_id(workspace_id)
    # A read-only mount of the volume in a throwaway container: the archive is
    # built inside Docker and returned as bytes, so the workspace never needs a
    # route to a Mac directory and the Mac never needs to be browsed.
    tar, err, code = docker(
        "run", "--rm",
        "--volume", f"{volume_name(workspace_id)}:/workspace:ro",
        "--network", "none",
        "--read-only",
        "--tmpfs", "/tmp:size=256m",
        "--user", "1000:1000",
        "--cap-drop", "ALL",
        "--security-opt", "no-new-privileges",
        RUNTIMES["python3"],
        "python3", "-c", EXPORT_SNIPPET, str(EXPORT_MAX_BYTES), str(EXPORT_UNCOMPRESSED_MAX_BYTES),
        binary=True, check=False, timeout=180,
        max_output_bytes=EXPORT_MAX_BYTES, fail_on_output_limit=True,
    )
    if code != 0 or not tar:
        raise Failure(500, f"export failed: {err.decode('utf-8','replace')[:400]}")
    return {"content_b64": base64.b64encode(tar).decode(), "bytes": len(tar), "media_type": "application/zip"}


