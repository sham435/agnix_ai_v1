#!/usr/bin/env python3
"""Shams AI workspace manager — the only component allowed to create containers.

The public Rails app talks to this over loopback HTTP with a bearer token; it
never sees the Docker socket. Everything here is argv arrays handed straight to
the docker CLI: no shell is ever spawned, so a path with spaces, a quote or a
backtick is just a filename.

Storage model: one named volume per workspace, mounted at /workspace. No host
directory is ever mounted, because on Docker Desktop any container can otherwise
ask for an arbitrary Mac path (verified: /Users/sham4/.ssh is mountable). A
workspace therefore cannot read the repo, the PostgreSQL volume, ~/.ssh or the
model files even in the worst case.
"""

