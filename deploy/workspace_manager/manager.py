def create_workspace(payload):
    workspace_id = safe_workspace_id(payload.get("id"))
    runtime = payload.get("runtime", "python3")
    image = RUNTIMES.get(runtime)
    if image is None:
        raise Failure(400, f"unsupported runtime {runtime}")

    with LOCK:
        if inspect_state(workspace_id)["state"] != "absent":
            raise Failure(409, "workspace already exists")

        _, _, code = docker(
            "volume", "create", volume_name(workspace_id),
            "--label", f"shams.workspace={workspace_id}",
            check=False,
        )
        if code != 0:
            raise Failure(500, "could not create workspace volume")

        # Ownership comes from the image's /workspace, not from a chown helper:
        # Docker re-initialises an empty named volume from the image directory
        # when the first container mounts it, which undoes any earlier chown.
        docker(
            "run", "--rm",
            "--volume", f"{volume_name(workspace_id)}:/workspace",
            "--network", "none",
            "--entrypoint", "/bin/sh",
            image,
            "-c", "chmod 755 /workspace",
            timeout=120, check=False,
        )

        argv = [
            "run", "-d",
            "--name", container_name(workspace_id),
            "--hostname", "workspace",
            "--label", f"shams.workspace={workspace_id}",
            "--user", "1000:1000",
            "--workdir", "/workspace",
            "--env", "HOME=/tmp",
            "--env", "PIP_NO_CACHE_DIR=1",
            "--env", "PIP_DISABLE_PIP_VERSION_CHECK=1",
            "--volume", f"{volume_name(workspace_id)}:/workspace",
            "--network", "none",
            "--read-only",
            "--tmpfs", f"/tmp:size={int(limit_for('tmpfs_mb', payload.get('tmpfs_mb')))}m",
            "--cap-drop", "ALL",
            "--security-opt", "no-new-privileges",
            "--pids-limit", str(int(limit_for("pids", payload.get("pids")))),
            "--memory", f"{int(limit_for('memory_mb', payload.get('memory_mb')))}m",
            "--memory-swap", f"{int(limit_for('memory_mb', payload.get('memory_mb')))}m",
            "--cpus", str(limit_for("cpus", payload.get("cpus"))),
            "--restart", "no",
            image,
            "sleep", "infinity",
        ]
        out, err, code = docker(*argv, timeout=180, check=False)
        if code != 0:
            docker("volume", "rm", volume_name(workspace_id), check=False)
            detail = (err or out).strip()[:1500]
            raise Failure(503, f"execution container failed to start: {detail}")

    # Ready means the container answers, not that the request was accepted.
    _, probe_err, probe_code = docker(
        "exec", container_name(workspace_id), "test", "-w", "/workspace", check=False, timeout=30
    )
    if probe_code != 0:
        destroy_workspace(workspace_id)
        raise Failure(503, f"workspace is not writable by its user: {probe_err.strip()[:300]}")

    time.sleep(0.1)
    return {"ok": True, "workspace_id": workspace_id, "status": workspace_status(workspace_id)}


def workspace_status(workspace_id):
    safe_workspace_id(workspace_id)
    state = inspect_state(workspace_id)
    _, resources, _ = docker(
        "stats", "--no-stream", "--format", "{{json .}}", container_name(workspace_id),
        check=False,
    )
    usage = {}
    for line in resources.strip().splitlines():
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        usage = {
            "cpu_percent": row.get("CPUPerc", "").rstrip("%"),
            "memory": row.get("MemUsage", ""),
            "blocked": row.get("BlockIO", ""),
        }
        break
    preview = preview_state(workspace_id)
    return {
        "workspace_id": workspace_id,
        "state": state["state"],
        "exit_code": state["exit_code"],
        "image": state["image"],
        "container": container_name(workspace_id) if state["state"] != "absent" else None,
        "volume": volume_name(workspace_id),
        "usage": usage,
        "preview": preview,
    }


def destroy_workspace(workspace_id, purge_volume=True):
    safe_workspace_id(workspace_id)
    docker("rm", "-f", preview_container(workspace_id), check=False, timeout=60)
    with LOCK:
        PREVIEWS.pop(workspace_id, None)
    out, err, code = docker("rm", "-f", container_name(workspace_id), check=False, timeout=90)
    detail = (out + err).lower()
    removed_container = code == 0 or "no such container" in detail
    volume_removed = False
    if purge_volume:
        _, err, vcode = docker("volume", "rm", volume_name(workspace_id), check=False, timeout=60)
        volume_removed = vcode == 0 or "no such volume" in err.lower() or "not found" in err.lower()
    if not removed_container:
        raise Failure(500, f"container could not be removed: {(out + err)[:400]}")
    return {
        "ok": True,
        "workspace_id": workspace_id,
        "container_removed": removed_container,
        "volume_removed": volume_removed,
    }


