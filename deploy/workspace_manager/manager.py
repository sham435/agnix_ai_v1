def write_file(workspace_id, path, content_bytes):
    safe_workspace_id(workspace_id)
    require_running(workspace_id)
    relative = safe_relative_path(path)
    ceiling = int(limit_for("file_bytes", None))
    if len(content_bytes) > ceiling:
        raise Failure(413, f"content exceeds {ceiling} bytes")

    parent = str(parent_of(relative))
    docker("exec", container_name(workspace_id), "mkdir", "-p", "--", f"/workspace/{parent}", timeout=40)

    # dd writes exactly what arrives on stdin; no quoting is involved at all.
    out, err, code = docker(
        "exec", "-i", container_name(workspace_id),
        "dd", f"of=/workspace/{relative}", "bs=1M",
        stdin=content_bytes, check=False, timeout=90,
    )
    if code != 0:
        raise Failure(500, f"write failed: {(err or out)[-400:]}")

    verify, _, vcode = docker(
        "exec", container_name(workspace_id),
        "wc", "-c", f"/workspace/{relative}", check=False, timeout=40,
    )
    reported = int((verify.split() or ["0"])[0]) if vcode == 0 else -1
    if reported != len(content_bytes):
        raise Failure(500, f"write verification mismatch: {reported} != {len(content_bytes)}")
    return {"ok": True, "path": relative, "bytes": reported}


def parent_of(relative):
    if "/" in relative:
        return relative.rsplit("/", 1)[0]
    return "."


def read_file(workspace_id, path, limit=None):
    safe_workspace_id(workspace_id)
    require_running(workspace_id)
    relative = safe_relative_path(path)
    ceiling = max(1, min(int(limit or limit_for("output_bytes", None)), DOCKER_OUTPUT_BYTES // 2))
    out, err, code = docker(
        "exec", container_name(workspace_id),
        "python3", "-c", READ_FILE_SNIPPET, f"/workspace/{relative}", str(ceiling),
        check=False, timeout=60,
    )
    if code != 0:
        raise Failure(404, f"read failed: {err[:300]}")
    try:
        result = json.loads(out)
    except json.JSONDecodeError as exc:
        raise Failure(500, "read returned unreadable output") from exc
    return {"path": relative, **result}


def list_files(workspace_id, depth_limit=None):
    safe_workspace_id(workspace_id)
    require_running(workspace_id)
    entries = int(limit_for("list_entries", depth_limit))
    out, err, code = docker(
        "exec", container_name(workspace_id),
        "python3", "-c", LIST_TREE, str(entries),
        check=False, timeout=60,
    )
    if code != 0:
        raise Failure(500, f"listing failed: {err[:400]}")
    try:
        return json.loads(out.strip().splitlines()[-1])
    except (json.JSONDecodeError, IndexError) as exc:
        raise Failure(500, "listing returned unreadable output") from exc


def remove_file(workspace_id, path):
    safe_workspace_id(workspace_id)
    require_running(workspace_id)
    relative = safe_relative_path(path)
    docker("exec", container_name(workspace_id), "rm", "-f", "--", f"/workspace/{relative}", timeout=40)
    return {"ok": True, "path": relative}


